"""Generate only the Chinese/English MIANCAK Android subtypes.
Auxiliary pages are selected inside the IME and are not Android languages.
"""
import xml.etree.ElementTree as ET

root = ET.Element("input-method", {
    "xmlns:android": "http://schemas.android.com/apk/res/android",
    "android:settingsActivity": "juloo.keyboard2.SettingsActivity",
    "android:supportsSwitchingToNextInputMethod": "true",
})
root.append(ET.Comment(" Generated by gen_method_xml.py. DO NOT EDIT. "))
for locale in ["zh_CN", "en_US"]:
    ET.SubElement(root, "subtype", {
        "android:label": "%s",
        "android:languageTag": locale.replace("_", "-"),
        "android:imeSubtypeLocale": locale,
        "android:imeSubtypeMode": "keyboard",
        "android:isAsciiCapable": "true",
        "android:imeSubtypeExtraValue": "script=latin,default_layout=miancak_qwerty" + (",dictionary=en_US" if locale == "en_US" else ""),
    })
ET.indent(root)
print(ET.tostring(root, encoding="utf-8", xml_declaration=True).decode("utf-8"))
